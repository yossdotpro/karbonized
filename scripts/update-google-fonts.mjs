/**
 * Regenerates `src/lib/fonts/google-fonts.ts` from the Google Fonts catalog.
 *
 *   node scripts/update-google-fonts.mjs
 *
 * The catalog is public and needs no key. Only what the font picker uses is
 * kept: the family name, its category and the weights it really has, so the
 * editor asks Google for weights that exist.
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SOURCE = 'https://fonts.google.com/metadata/fonts';
const OUTPUT = path.join(
	path.dirname(fileURLToPath(import.meta.url)),
	'..',
	'src',
	'lib',
	'fonts',
	'google-fonts.ts',
);

/** The categories Google uses, as the picker shows them. */
const CATEGORIES = {
	'Sans Serif': 'sans',
	Serif: 'serif',
	Display: 'display',
	Handwriting: 'handwriting',
	Monospace: 'mono',
};

const weightsOf = (font) => {
	// `fonts` is keyed by variant: "400", "700italic", "regular"…
	const weights = new Set();

	Object.keys(font.fonts ?? {}).forEach((variant) => {
		const weight = Number.parseInt(variant, 10);
		if (Number.isFinite(weight)) weights.add(weight);
	});

	// Variable fonts describe their range with a `wght` axis.
	(font.axes ?? []).forEach((axis) => {
		if (axis.tag !== 'wght') return;
		for (let weight = 100; weight <= 900; weight += 100) {
			if (weight >= axis.min && weight <= axis.max) weights.add(weight);
		}
	});

	return weights.size > 0 ? [...weights].sort((a, b) => a - b) : [400];
};

const main = async () => {
	const response = await fetch(SOURCE);
	if (!response.ok) {
		throw new Error(`Google Fonts answered ${response.status}`);
	}

	const catalog = await response.json();
	const families = (catalog.familyMetadataList ?? [])
		.filter((font) => font.family && CATEGORIES[font.category])
		.map((font) => ({
			family: font.family,
			category: CATEGORIES[font.category],
			weights: weightsOf(font),
			// How much the family is used, to show the common ones first.
			popularity: font.popularity ?? Number.MAX_SAFE_INTEGER,
		}))
		.sort((a, b) => a.popularity - b.popularity);

	const rows = families
		.map(
			({ family, category, weights }) =>
				`\t['${family.replace(/'/g, "\\'")}', '${category}', '${weights.join(',')}'],`,
		)
		.join('\n');

	const file = `/**
 * The Google Fonts catalog: family, category and the weights it has.
 *
 * Generated by \`node scripts/update-google-fonts.mjs\`; do not edit by hand.
 * ${families.length} families, most used first.
 */

export type GoogleFontRow = readonly [
	family: string,
	category: string,
	weights: string,
];

export const GOOGLE_FONT_ROWS: readonly GoogleFontRow[] = [
${rows}
];
`;

	// Formatted here, so a regenerated catalog never fails the lint.
	const prettier = await import('prettier');
	const options = await prettier.resolveConfig(OUTPUT);
	const formatted = await prettier.format(file, {
		...options,
		filepath: OUTPUT,
	});

	await writeFile(OUTPUT, formatted, 'utf8');
	console.log(`${families.length} families written to ${OUTPUT}`);
};

await main();
